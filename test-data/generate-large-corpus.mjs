#!/usr/bin/env node
/**
 * Generate a large set of synthetic MIB modules for performance testing.
 *
 * The handwritten fixtures in test-data/mibs are for behaviour; this is for
 * volume. Each generated module is self-contained apart from SNMPv2-SMI, and
 * anchors itself under a distinct enterprise number, so the modules merge into
 * one wide tree the way a real vendor MIB collection does.
 *
 * Usage:
 *   node test-data/generate-large-corpus.mjs [modules] [objects-per-module] [outDir]
 *
 * Defaults: 60 modules x 200 objects (~12k nodes, ~2 MB), written to
 * test-data/generated/ which is git-ignored.
 *
 * Then drag the generated directory onto the app, or pick all the files in the
 * file dialog.
 */

import { mkdirSync, writeFileSync, readdirSync, unlinkSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const HERE = dirname(fileURLToPath(import.meta.url));

const moduleCount = Number(process.argv[2] ?? 60);
const objectsPerModule = Number(process.argv[3] ?? 200);
const outDir = resolve(process.argv[4] ?? join(HERE, 'generated'));

if (!Number.isInteger(moduleCount) || moduleCount < 1) {
  console.error(`Invalid module count: ${process.argv[2]}`);
  process.exit(1);
}
if (!Number.isInteger(objectsPerModule) || objectsPerModule < 1) {
  console.error(`Invalid objects-per-module: ${process.argv[3]}`);
  process.exit(1);
}

// Enterprise numbers start well past the fixtures so the two sets can be
// loaded side by side without colliding.
const ENTERPRISE_BASE = 900000;

// Depth of the OBJECT IDENTIFIER chain between the module root and its leaves,
// so the generated tree is deep enough to be worth expanding and collapsing.
const GROUP_DEPTH = 4;

function generateModule(index) {
  const name = `GEN-${index}-MIB`;
  const lines = [];

  lines.push(`${name} DEFINITIONS ::= BEGIN`);
  lines.push('');
  lines.push('-- Generated by test-data/generate-large-corpus.mjs. Do not edit.');
  lines.push('');
  lines.push('IMPORTS');
  lines.push('    MODULE-IDENTITY, OBJECT-TYPE, Integer32,');
  lines.push('    enterprises');
  lines.push('        FROM SNMPv2-SMI');
  lines.push('    DisplayString');
  lines.push('        FROM SNMPv2-TC;');
  lines.push('');
  lines.push(`genRoot${index} MODULE-IDENTITY`);
  lines.push('    LAST-UPDATED "202601010000Z"');
  lines.push('    ORGANIZATION "MIB Browser Test Data"');
  lines.push('    CONTACT-INFO "https://github.com/shmuto/mib-browser"');
  lines.push('    DESCRIPTION');
  lines.push(`        "Synthetic module ${index} of the generated performance corpus."`);
  lines.push(`    ::= { enterprises ${ENTERPRISE_BASE + index} }`);
  lines.push('');

  let parent = `genRoot${index}`;
  for (let depth = 1; depth <= GROUP_DEPTH; depth++) {
    const group = `genGroup${index}x${depth}`;
    lines.push(`${group} OBJECT IDENTIFIER ::= { ${parent} ${depth} }`);
    parent = group;
  }
  lines.push('');

  for (let object = 1; object <= objectsPerModule; object++) {
    // Alternate the syntax so the details panel has something to vary on
    const syntax = object % 3 === 0 ? 'DisplayString' : 'Integer32';
    lines.push(`genObj${index}x${object} OBJECT-TYPE`);
    lines.push(`    SYNTAX      ${syntax}`);
    lines.push('    MAX-ACCESS  read-only');
    lines.push(`    STATUS      ${object % 17 === 0 ? 'deprecated' : 'current'}`);
    lines.push('    DESCRIPTION');
    lines.push(`        "Object ${object} of synthetic module ${index}. The text is padded out`);
    lines.push('         to a realistic length so that description matching during a search');
    lines.push('         costs what it would cost on a real MIB collection."');
    lines.push(`    ::= { ${parent} ${object} }`);
    lines.push('');
  }

  lines.push('END');
  return { fileName: `${name}.txt`, content: lines.join('\n') };
}

mkdirSync(outDir, { recursive: true });

// Clear previously generated files so a smaller run does not leave strays
for (const existing of readdirSync(outDir)) {
  if (/^GEN-\d+-MIB\.txt$/.test(existing)) {
    unlinkSync(join(outDir, existing));
  }
}

let totalBytes = 0;
for (let index = 0; index < moduleCount; index++) {
  const { fileName, content } = generateModule(index);
  writeFileSync(join(outDir, fileName), content);
  totalBytes += content.length;
}

const nodeCount = moduleCount * (1 + GROUP_DEPTH + objectsPerModule);
console.log(
  `Wrote ${moduleCount} modules (${objectsPerModule} objects each, ~${nodeCount} nodes, ` +
  `${(totalBytes / 1024 / 1024).toFixed(2)} MB) to ${outDir}`
);
